function Arbitrage:PopulatePropMenu()
    local contents = {}

    for k, v in pairs(data) do
        table.insert( contents, {
            type = "header",
            text = k
        })

        for k2, v2 in ipairs(v) do
            table.insert( contents, {
                type = "model",
                model = v2
            })
        end
    end

    spawnmenu.AddPropCategory("NewSpawn", "Список пропов", contents, "icon16/box.png")
end